using System.Collections.Generic;
using System.IO;
using System.Text.Json;
using System.Threading.Tasks;
using Volo.Abp.DependencyInjection;
using Volo.Abp.VirtualFileSystem;

namespace OpenTms.MasterData.Seed;

public sealed record CurrencySeedRecord(string IsoCode, int? IsoNumeric, int? MinorUnits, string? Symbol, Dictionary<string, string?> Names);

public sealed record CountrySeedRecord(string IsoAlpha2, string IsoAlpha3, int? IsoNumeric, Dictionary<string, string?> Names, string? DefaultCurrency, string? PrimaryTimeZoneId);

public sealed record AddressTypeSeedRecord(string Kind, Dictionary<string, string?> Names);

/// <summary>
/// Reads the embedded seed files of MasterData.Domain.Shared (generated by scripts/masterdata-seed/generate.mjs)
/// through the ABP virtual file system.
/// </summary>
public class MasterDataSeedData : ITransientDependency
{
    public const string CurrenciesFile = "/Seed/iso-4217-currencies.json";
    public const string CountriesFile = "/Seed/iso-3166-countries.json";
    public const string AddressTypesFile = "/Seed/address-types.json";

    private static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web);

    private readonly IVirtualFileProvider _fileProvider;

    public MasterDataSeedData(IVirtualFileProvider fileProvider)
    {
        _fileProvider = fileProvider;
    }

    public Task<List<CurrencySeedRecord>> GetCurrenciesAsync() => ReadAsync<CurrencySeedRecord>(CurrenciesFile);

    public Task<List<CountrySeedRecord>> GetCountriesAsync() => ReadAsync<CountrySeedRecord>(CountriesFile);

    public Task<List<AddressTypeSeedRecord>> GetAddressTypesAsync() => ReadAsync<AddressTypeSeedRecord>(AddressTypesFile);

    private async Task<List<T>> ReadAsync<T>(string path)
    {
        var file = _fileProvider.GetFileInfo(path);
        if (!file.Exists)
        {
            throw new FileNotFoundException($"Master Data seed file '{path}' is not embedded.");
        }

        await using var stream = file.CreateReadStream();
        return await JsonSerializer.DeserializeAsync<List<T>>(stream, JsonOptions) ?? [];
    }
}
